CREATE TABLE notificacao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT       NOT NULL REFERENCES empresa (id),
    destinatario_id BIGINT       NOT NULL REFERENCES colaborador (id),
    tipo            VARCHAR(40)  NOT NULL,
    mensagem        VARCHAR(400) NOT NULL,
    link            VARCHAR(200),              -- a tela do front que a notificação abre
    chave_unica     VARCHAR(120),              -- só nos avisos da rotina diária (ver abaixo)
    lida_em         TIMESTAMPTZ,               -- nulo = não lida
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- A-05: a rotina diária ("suas férias vencem em...") pode rodar duas vezes no mesmo dia
    -- (a API reiniciou, por exemplo). Esta restrição garante que o mesmo aviso não sai duas vezes.
    -- As notificações dos eventos do fluxo deixam a chave nula, e no PostgreSQL vários NULL
    -- não contam como repetidos: elas não são afetadas.
    CONSTRAINT uk_notificacao_chave UNIQUE (destinatario_id, chave_unica)
);

-- O sino busca "as minhas, das mais novas para as mais antigas".
CREATE INDEX ix_notificacao_destinatario ON notificacao (destinatario_id, id DESC);
