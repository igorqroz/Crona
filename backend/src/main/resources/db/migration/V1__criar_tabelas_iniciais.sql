-- ---------------------------------------------------------------------
-- Empresa: cada cliente do Crona (multi-tenant)
-- ---------------------------------------------------------------------
CREATE TABLE empresa (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social  VARCHAR(200) NOT NULL,
    nome_fantasia VARCHAR(200),
    cnpj          CHAR(14)     NOT NULL UNIQUE,  -- só números, sem pontuação
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_empresa_cnpj_numerico CHECK (cnpj ~ '^[0-9]{14}$')
);


-- ---------------------------------------------------------------------
-- Configuração de férias: regras da empresa (valor nulo = regra desligada)
-- ---------------------------------------------------------------------
CREATE TABLE configuracao_ferias (
    id                               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id                       BIGINT      NOT NULL UNIQUE REFERENCES empresa (id),
    percentual_minimo_trabalhando    INTEGER,                      -- EMP-01
    limite_ferias_simultaneas_empresa INTEGER,                     -- EMP-04
    antecedencia_minima_dias         INTEGER     NOT NULL DEFAULT 30, -- EMP-03
    criado_em                        TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em                    TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_config_percentual  CHECK (percentual_minimo_trabalhando BETWEEN 0 AND 100),
    CONSTRAINT ck_config_limite      CHECK (limite_ferias_simultaneas_empresa > 0),
    CONSTRAINT ck_config_antecedencia CHECK (antecedencia_minima_dias >= 30) -- CLT-07
);


-- ---------------------------------------------------------------------
-- Departamento
-- ---------------------------------------------------------------------
CREATE TABLE departamento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    BIGINT       NOT NULL REFERENCES empresa (id),
    nome          VARCHAR(100) NOT NULL,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_departamento_nome UNIQUE (empresa_id, nome)
);


-- ---------------------------------------------------------------------
-- Colaborador: dados de trabalho + login
-- ---------------------------------------------------------------------
CREATE TABLE colaborador (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT       NOT NULL REFERENCES empresa (id),
    departamento_id BIGINT       REFERENCES departamento (id),
    gestor_id       BIGINT       REFERENCES colaborador (id),  -- auto-relacionamento
    nome            VARCHAR(150) NOT NULL,
    email           VARCHAR(254) NOT NULL,
    senha_hash      VARCHAR(100) NOT NULL,                      -- BCrypt, nunca a senha
    perfil          VARCHAR(20)  NOT NULL DEFAULT 'COLABORADOR',
    cargo           VARCHAR(100),
    data_admissao   DATE         NOT NULL,
    ativo           BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_colaborador_perfil    CHECK (perfil IN ('COLABORADOR', 'GESTOR', 'ADMIN')),
    CONSTRAINT ck_colaborador_gestor    CHECK (gestor_id <> id)  -- ninguém é gestor de si mesmo
);

-- E-mail único sem diferenciar maiúsculas: "Igor@x.com" = "igor@x.com"
CREATE UNIQUE INDEX uk_colaborador_email ON colaborador (lower(email));


-- ---------------------------------------------------------------------
-- Período aquisitivo: cada 12 meses trabalhados
-- ---------------------------------------------------------------------
CREATE TABLE periodo_aquisitivo (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id         BIGINT      NOT NULL REFERENCES colaborador (id),
    numero                 INTEGER     NOT NULL,
    data_inicio            DATE        NOT NULL,
    data_fim               DATE        NOT NULL,
    data_limite_concessao  DATE        NOT NULL,           -- CLT-03
    faltas_injustificadas  INTEGER     NOT NULL DEFAULT 0, -- CLT-02
    dias_direito           INTEGER     NOT NULL DEFAULT 30,
    criado_em              TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_periodo_numero    UNIQUE (colaborador_id, numero),
    CONSTRAINT ck_periodo_numero    CHECK (numero > 0),
    CONSTRAINT ck_periodo_datas     CHECK (data_fim > data_inicio AND data_limite_concessao > data_fim),
    CONSTRAINT ck_periodo_faltas    CHECK (faltas_injustificadas >= 0),
    CONSTRAINT ck_periodo_direito   CHECK (dias_direito IN (0, 12, 18, 24, 30))
);


-- ---------------------------------------------------------------------
-- Solicitação de férias
-- ---------------------------------------------------------------------
CREATE TABLE solicitacao_ferias (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id        BIGINT      NOT NULL REFERENCES colaborador (id),
    periodo_aquisitivo_id BIGINT      NOT NULL REFERENCES periodo_aquisitivo (id),
    data_inicio           DATE        NOT NULL,
    data_fim              DATE        NOT NULL,
    dias_gozo             INTEGER     NOT NULL,
    dias_abono            INTEGER     NOT NULL DEFAULT 0,  -- CLT-06
    status                VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    decidido_por_id       BIGINT      REFERENCES colaborador (id),
    decidido_em           TIMESTAMPTZ,
    motivo_recusa         VARCHAR(500),
    criado_em             TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_solicitacao_status CHECK (status IN ('PENDENTE', 'APROVADA', 'RECUSADA', 'CANCELADA')),
    CONSTRAINT ck_solicitacao_datas  CHECK (data_fim >= data_inicio),
    CONSTRAINT ck_solicitacao_dias   CHECK (dias_gozo >= 5),            -- CLT-04: menor parte possível
    CONSTRAINT ck_solicitacao_abono  CHECK (dias_abono BETWEEN 0 AND 10) -- CLT-06: no máximo 1/3 de 30
);


-- ---------------------------------------------------------------------
-- Negociação: troca de período entre dois colaboradores
-- ---------------------------------------------------------------------
CREATE TABLE negociacao (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id             BIGINT      NOT NULL REFERENCES colaborador (id),
    colega_id                  BIGINT      NOT NULL REFERENCES colaborador (id),
    solicitacao_colega_id      BIGINT      NOT NULL REFERENCES solicitacao_ferias (id),
    solicitacao_solicitante_id BIGINT      REFERENCES solicitacao_ferias (id),
    status                     VARCHAR(30) NOT NULL DEFAULT 'AGUARDANDO_COLEGA',
    decidido_por_id            BIGINT      REFERENCES colaborador (id),
    decidido_em                TIMESTAMPTZ,
    criado_em                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_negociacao_pessoas CHECK (solicitante_id <> colega_id),
    CONSTRAINT ck_negociacao_status  CHECK (status IN (
        'AGUARDANDO_COLEGA', 'AGUARDANDO_SOLICITANTE', 'AGUARDANDO_GESTOR',
        'APROVADA', 'RECUSADA', 'CANCELADA'))
);


-- ---------------------------------------------------------------------
-- Proposta de negociação: cada rodada (a vigente é a mais recente)
-- ---------------------------------------------------------------------
CREATE TABLE proposta_negociacao (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negociacao_id      BIGINT       NOT NULL REFERENCES negociacao (id),
    autor_id           BIGINT       NOT NULL REFERENCES colaborador (id),
    inicio_solicitante DATE         NOT NULL,
    fim_solicitante    DATE         NOT NULL,
    inicio_colega      DATE         NOT NULL,
    fim_colega         DATE         NOT NULL,
    mensagem           VARCHAR(500),
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_proposta_datas CHECK (fim_solicitante >= inicio_solicitante AND fim_colega >= inicio_colega)
);


-- ---------------------------------------------------------------------
-- Período bloqueado (EMP-05): departamento nulo = empresa toda
-- ---------------------------------------------------------------------
CREATE TABLE periodo_bloqueado (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT       NOT NULL REFERENCES empresa (id),
    departamento_id BIGINT       REFERENCES departamento (id),
    data_inicio     DATE         NOT NULL,
    data_fim        DATE         NOT NULL,
    motivo          VARCHAR(200) NOT NULL,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_bloqueio_datas CHECK (data_fim >= data_inicio)
);


-- ---------------------------------------------------------------------
-- Feriado (CLT-05): empresa nula = feriado nacional
-- ---------------------------------------------------------------------
CREATE TABLE feriado (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    BIGINT       REFERENCES empresa (id),
    data          DATE         NOT NULL,
    descricao     VARCHAR(100) NOT NULL,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- NULLS NOT DISTINCT: impede dois feriados nacionais (empresa nula) na mesma data
    CONSTRAINT uk_feriado_data UNIQUE NULLS NOT DISTINCT (empresa_id, data)
);


-- ---------------------------------------------------------------------
-- Índices nas chaves estrangeiras
-- O PostgreSQL NÃO cria índice em FK sozinho. Sem eles, buscas como
-- "solicitações do colaborador X" leem a tabela inteira.
-- ---------------------------------------------------------------------
CREATE INDEX ix_departamento_empresa       ON departamento (empresa_id);
CREATE INDEX ix_colaborador_empresa        ON colaborador (empresa_id);
CREATE INDEX ix_colaborador_departamento   ON colaborador (departamento_id);
CREATE INDEX ix_colaborador_gestor         ON colaborador (gestor_id);
CREATE INDEX ix_periodo_colaborador        ON periodo_aquisitivo (colaborador_id);
CREATE INDEX ix_solicitacao_colaborador    ON solicitacao_ferias (colaborador_id);
CREATE INDEX ix_solicitacao_periodo        ON solicitacao_ferias (periodo_aquisitivo_id);
CREATE INDEX ix_solicitacao_datas          ON solicitacao_ferias (data_inicio, data_fim); -- busca de sobreposição
CREATE INDEX ix_negociacao_solicitante     ON negociacao (solicitante_id);
CREATE INDEX ix_negociacao_colega          ON negociacao (colega_id);
CREATE INDEX ix_proposta_negociacao        ON proposta_negociacao (negociacao_id);
CREATE INDEX ix_bloqueio_empresa           ON periodo_bloqueado (empresa_id);
