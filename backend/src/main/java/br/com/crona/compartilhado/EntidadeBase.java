package br.com.crona.compartilhado;

import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.Instant;

/**
 * Campos que quase toda tabela do Crona tem: id, criado_em e atualizado_em.
 *
 * {@code @MappedSuperclass} = esta classe não é uma tabela. Ela só "empresta" os
 * campos para as entidades que a estendem (Empresa, Departamento...).
 */
@MappedSuperclass
public abstract class EntidadeBase {

    // IDENTITY: quem gera o id é o banco (GENERATED BY DEFAULT AS IDENTITY no V1).
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // O Hibernate preenche sozinho ao inserir; depois nunca mais muda.
    @CreationTimestamp
    @Column(name = "criado_em", nullable = false, updatable = false)
    private Instant criadoEm;

    // O Hibernate atualiza sozinho a cada alteração.
    @UpdateTimestamp
    @Column(name = "atualizado_em", nullable = false)
    private Instant atualizadoEm;

    public Long getId() {
        return id;
    }

    public Instant getCriadoEm() {
        return criadoEm;
    }

    public Instant getAtualizadoEm() {
        return atualizadoEm;
    }
}
